"""Regenerate the pointwise target table in src/layout/pointwise.rs.

rc4's view/permute propagation treats a node as elementwise when torch tags its
op `torch.Tag.pointwise` (`PropagateViewCopyPermutePass.is_elementwise`,
backends/transforms/propagate_view_copy_permute_pass.py:460-470). RETAB has no
torch at lowering time, so this script evaluates that tag test ahead of time for
every edge target in tests/fixtures/rc4_arm_edge_targets.tsv and writes the
tagged ones into the generated block of src/layout/pointwise.rs.

Run it with the Python environment that has the pinned ExecuTorch and torch
installed, from a directory outside any checkout:

    python -P scripts/gen_pointwise_targets.py           # rewrite the table
    python -P scripts/gen_pointwise_targets.py --check   # fail if it is stale

Each target resolves through the edge dialect and reads `EdgeOpOverload._op.tags`,
the attribute rc4 reads. A target that does not resolve is an error: the fixture
and the installed ExecuTorch disagree.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "tests" / "fixtures" / "rc4_arm_edge_targets.tsv"
OUTPUT = ROOT / "src" / "layout" / "pointwise.rs"
BEGIN = "// BEGIN GENERATED by scripts/gen_pointwise_targets.py; do not edit."
END = "// END GENERATED"


def fixture_targets(path: Path) -> list[str]:
    targets = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            targets.append(line.split("\t", 1)[0])
    return targets


def pointwise_targets(targets: list[str]) -> list[str]:
    import torch
    from executorch.exir.dialects._ops import ops as exir_ops

    # The tosa_mxfp namespace is registered only when its op modules load.
    import executorch.backends.arm.ao_ext.ops.mxfp_conv2d_op  # noqa: F401
    import executorch.backends.arm.ao_ext.ops.mxfp_linear_op  # noqa: F401

    tagged = []
    unresolved = []
    for target in targets:
        namespace, rest = target.split(".", 1)
        name, overload = rest.rsplit(".", 1)
        try:
            edge_op = getattr(getattr(getattr(exir_ops.edge, namespace), name), overload)
            tags = edge_op._op.tags
        except (AttributeError, RuntimeError) as error:
            unresolved.append(f"{target}: {error}")
            continue
        if namespace == "aten":
            aten_tags = getattr(getattr(torch.ops.aten, name), overload).tags
            if list(aten_tags) != list(tags):
                raise SystemExit(f"{target}: edge tags {tags} differ from aten tags {aten_tags}")
        if torch.Tag.pointwise in tags:
            tagged.append(target)
    if unresolved:
        raise SystemExit("unresolved fixture targets:\n" + "\n".join(unresolved))
    return sorted(tagged)


def generated_block(tagged: list[str], torch_version: str) -> str:
    lines = [
        BEGIN,
        f"// Source: tests/fixtures/rc4_arm_edge_targets.tsv, torch {torch_version}.",
        "pub(crate) const POINTWISE_TARGETS: &[&str] = &[",
        *(f'    "{target}",' for target in tagged),
        "];",
        END,
    ]
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    start = text.find(BEGIN)
    end = text.find(END, start)
    if start < 0 or end < 0:
        raise SystemExit(f"{OUTPUT} has no generated block between {BEGIN!r} and {END!r}")
    return text[:start] + block + text[end + len(END) :]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the table is stale")
    args = parser.parse_args()

    import torch

    targets = fixture_targets(FIXTURE)
    tagged = pointwise_targets(targets)
    torch_version = torch.__version__.split("+", 1)[0]
    current = OUTPUT.read_text()
    updated = replace_block(current, generated_block(tagged, torch_version))
    print(f"{len(tagged)} of {len(targets)} fixture targets are tagged pointwise", file=sys.stderr)
    if args.check:
        if updated != current:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; rerun without --check", file=sys.stderr)
            return 1
        return 0
    if updated != current:
        OUTPUT.write_text(updated)
        print(f"updated {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
