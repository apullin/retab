/// Copies a data-movement node may cross without changing their meaning.
///
/// Mirrors rc4's `PropagateViewCopyPermutePass._TRANSPARENT_TARGETS`
/// (`backends/transforms/propagate_view_copy_permute_pass.py:63-66`):
/// `_clone_dim_order` and `_to_dim_order_copy`. RETAB's spellings of the same
/// ops are added: the namespace-less forms `fx_target` already accepts, and
/// `aten._to_copy.default`, which RETAB's ports emit wherever rc4 emits
/// `_to_dim_order_copy` (`IrRewriteCursor::dtype_cast`). rc4's set has no alias
/// op, and `aten.alias_copy.default` is neither transparent nor pointwise there.
pub(crate) const TRANSPARENT_COPY_TARGETS: &[&str] = &[
    "_clone_dim_order.default",
    "_to_dim_order_copy.default",
    "aten._to_copy.default",
    "dim_order_ops._clone_dim_order.default",
    "dim_order_ops._to_dim_order_copy.default",
];

/// Whether torch tags `target` `Tag.pointwise`: the tag test in rc4's
/// `is_elementwise` (`backends/transforms/propagate_view_copy_permute_pass.py:467-469`).
pub(crate) fn is_pointwise(target: &str) -> bool {
    POINTWISE_TARGETS.binary_search(&target).is_ok()
}

/// Whether `target` is a transparent copy: rc4's base `is_transparent`
/// (`backends/transforms/propagate_view_copy_permute_pass.py:419-426`).
///
/// rc4's `is_elementwise` also accepts every transparent target, so a layout
/// pass asks both: `is_pointwise(t) || is_transparent_copy(t)`. Rank-changing
/// views may cross pointwise ops but not transparent ones (`:499-507`).
pub(crate) fn is_transparent_copy(target: &str) -> bool {
    TRANSPARENT_COPY_TARGETS.binary_search(&target).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    const FIXTURE: &str = include_str!("../../tests/fixtures/rc4_arm_edge_targets.tsv");

    fn fixture_targets() -> Vec<&'static str> {
        FIXTURE
            .lines()
            .map(str::trim)
            .filter(|line| !line.is_empty() && !line.starts_with('#'))
            .filter_map(|line| line.split('\t').next())
            .collect()
    }

    fn assert_strictly_sorted(table: &[&str]) {
        for pair in table.windows(2) {
            assert!(
                pair[0] < pair[1],
                "{:?} must sort before {:?}",
                pair[0],
                pair[1]
            );
        }
    }

    #[test]
    fn pointwise_table_is_sorted_and_drawn_from_the_rc4_fixture() {
        assert_strictly_sorted(POINTWISE_TARGETS);
        let fixture = fixture_targets();
        for target in POINTWISE_TARGETS {
            assert!(
                fixture.contains(target),
                "{target} is not in rc4_arm_edge_targets.tsv"
            );
        }
    }

    #[test]
    fn transparent_table_is_sorted() {
        assert_strictly_sorted(TRANSPARENT_COPY_TARGETS);
    }

    /// Spot checks against torch 2.15's tags, including ops whose tag is easy
    /// to guess wrong.
    #[test]
    fn pointwise_follows_torch_tags() {
        for target in [
            "aten.add.Tensor",
            "aten.relu.default",
            "aten.sigmoid.default",
            "aten.where.self",
            "aten.eq.Scalar",
            "aten.clamp.Tensor",
            "aten.masked_fill.Scalar",
        ] {
            assert!(is_pointwise(target), "{target} is tagged pointwise");
        }
        for target in [
            // Not tagged in torch 2.15, though they compute elementwise.
            "aten.hardswish.default",
            "aten.where.ScalarOther",
            "aten.prelu.default",
            // Data movement and reductions.
            "aten.permute_copy.default",
            "aten.view_copy.default",
            "aten.mean.dim",
            "aten.alias_copy.default",
            "dim_order_ops._clone_dim_order.default",
            // TOSA dialect ops carry no torch tags.
            "backend.tosa.RESCALE.default",
        ] {
            assert!(!is_pointwise(target), "{target} is not tagged pointwise");
        }
    }

    #[test]
    fn transparent_copies_are_rc4s_dim_order_copies_and_retab_spellings() {
        for target in [
            "dim_order_ops._clone_dim_order.default",
            "dim_order_ops._to_dim_order_copy.default",
            "aten._to_copy.default",
        ] {
            assert!(is_transparent_copy(target), "{target} is transparent");
        }
        for target in [
            "aten.alias_copy.default",
            "aten.clone.default",
            "aten.relu.default",
            "backend.tosa.RESCALE.default",
        ] {
            assert!(!is_transparent_copy(target), "{target} is not transparent");
        }
    }
}
