//! no torch at lowering time, so `scripts/gen_pointwise_targets.py` evaluates
//! that tag test ahead of time over `tests/fixtures/rc4_arm_edge_targets.tsv`,
//! the edge targets rc4's Arm backend references. Regenerate the table whenever
//! the fixture or the torch pin changes; the tests below catch a hand edit that
//! breaks its order or adds a target the fixture lacks.
//!
//! Only the base pass's answers live here. rc4's TOSA overrides
